let language = "zh-CN";

export function setLanguage(value) {
  language = value === "en" ? "en" : "zh-CN";
  document.documentElement.lang = language;
  return language;
}

export function tr(message, values = {}) {
  const localized = language === "en" ? message : Object.hasOwn(chinese, message) ? chinese[message] : message;
  return localized.replace(/\{([a-z]+)\}/g, (match, name) => Object.hasOwn(values, name) ? String(values[name]) : match);
}

export function toolLabel(name) {
  const translated = tr(name);
  return translated === name ? name.replaceAll("_", " ").replaceAll(".", " ") : translated;
}

export function errorLabel(message) {
  if (language === "zh-CN" && message.startsWith("OpenCode v2 executable unavailable")) {
    return "找不到 OpenCode v2 可执行文件。请运行 scripts/install-opencode.sh，或设置 MYGO_WORK_OPENCODE。";
  }
  return tr(message);
}
